export const defaultShots: Shot[] = selects.map((s, i) => ({
  startAt: s.at,
  durationInFrames: s.frames,
  zoom: i % 2 === 0 ? 1 : -1,
  voice: Boolean(s.voice),
  voiceGain: s.gain ?? 1,
  caption: s.voice,
  hero: Boolean(s.hero),
}));

export const shotStarts = (shots: Shot[]) =>
  shots.reduce<number[]>(
    (acc, s, i) => [
      ...acc,
      i === 0 ? 0 : acc[i - 1] + shots[i - 1].durationInFrames,
    ],
    [],
  );

const starts = shotStarts(defaultShots);
const flexStart = starts[8];
const heroStart = starts[defaultShots.findIndex((s) => s.hero)];

