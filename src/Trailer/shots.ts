import { z } from "zod";

export const FPS = 30;

export const shotSchema = z.object({
  // Path inside public/. Falls back to the trailer's `source` when omitted.
  src: z.string().optional(),
  // Where in the source clip this shot starts, in seconds.
  startAt: z.number().min(0),
  durationInFrames: z.number().int().positive(),
  // Subtle push-in (1) or pull-out (-1).
  zoom: z.union([z.literal(1), z.literal(-1)]).default(1),
  // Play this shot's own audio (a line of dialogue, in sync).
  voice: z.boolean().default(false),
  voiceGain: z.number().min(0).max(4).default(1),
  caption: z.string().optional(),
  // The drop: white flash and the biggest hit in the score.
  hero: z.boolean().default(false),
});

// A line of dialogue laid over other shots (J-cut / voice-over).
export const voiceoverSchema = z.object({
  from: z.number().int().min(0), // trailer frame where the line starts
  startAt: z.number().min(0), // seconds into the source
  durationInFrames: z.number().int().positive(),
  caption: z.string(),
});

export const trailerSchema = z.object({
  // Main footage file inside public/.
  source: z.string(),
  // Original score inside public/ (generated by scripts/make_score.py).
  score: z.string(),
  showSafeZone: z.boolean(),
  titleText: z.string(),
  endText: z.string(),
  shots: z.array(shotSchema).min(3),
  voiceovers: z.array(voiceoverSchema),
});

export type Shot = z.infer<typeof shotSchema>;
export type Voiceover = z.infer<typeof voiceoverSchema>;
export type TrailerProps = z.infer<typeof trailerSchema>;

